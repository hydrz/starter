import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// yaml is not a root dependency; resolve it from the pnpm store so the
// generator stays dependency-light. Fail with a clear message if absent.
let parse;
try {
  parse = createRequire(import.meta.url)("yaml").parse;
} catch {
  const storePath = join(repositoryRoot, "node_modules", ".pnpm");
  const yamlDir = readdirSync(storePath).find((entry) => entry.startsWith("yaml@"));
  if (!yamlDir) {
    console.error("yaml package not found under node_modules/.pnpm; run pnpm install first.");
    process.exit(1);
  }
  ({ parse } = await import(
    pathToFileURL(join(storePath, yamlDir, "node_modules", "yaml", "browser", "index.js")).href
  ));
}
const specDir = join(repositoryRoot, "spec", "generated");

if (!existsSync(specDir)) {
  console.error(`Spec directory not found: ${specDir}`);
  process.exit(1);
}

const files = readdirSync(specDir).sort();
for (const file of files) {
  if (file.endsWith(".openapi.yaml") && file !== "openapi.yaml") {
    const featureName = file.replace(".openapi.yaml", "");
    const pkgName = `${featureName}api`;
    const targetDir = join(repositoryRoot, "internal", "api", pkgName);
    console.log(`Generating Go server with ogen: ${featureName} -> ${pkgName}...`);
    execSync(
      `go tool ogen --target ${targetDir} --package ${pkgName} --clean ${join(specDir, file)}`,
      {
        cwd: repositoryRoot,
        stdio: "inherit",
      },
    );

    // permissions_gen.go maps operationID -> "resource:action" from the
    // x-permission extension, so Casbin authorization stays declared in the
    // TypeSpec contract instead of hand-written route tables. Written in the
    // same loop as ogen (after --clean) so it is not wiped by regeneration.
    const permissions = extractPermissions(join(specDir, file));
    writePermissionsFile(targetDir, pkgName, permissions);
  }
}

function extractPermissions(specPath) {
  const spec = parse(readFileSync(specPath, "utf8"));
  const permissions = {};
  for (const pathItem of Object.values(spec.paths ?? {})) {
    for (const operation of Object.values(pathItem ?? {})) {
      if (!operation || typeof operation !== "object" || !operation.operationId) {
        continue;
      }
      const permission = operation["x-permission"];
      if (typeof permission === "string" && permission !== "") {
        permissions[operation.operationId] = permission;
      }
    }
  }
  return permissions;
}

function writePermissionsFile(targetDir, pkgName, permissions) {
  if (Object.keys(permissions).length === 0) {
    return;
  }
  const entries = Object.entries(permissions).sort(([a], [b]) => a.localeCompare(b));
  const body = entries
    .map(([operationID, permission]) => `\t${JSON.stringify(operationID)}: ${JSON.stringify(permission)},`)
    .join("\n");
  const content = `// Code generated by tools/generate-server.mjs from the TypeSpec contract. DO NOT EDIT.

package ${pkgName}

// Permissions maps operationID to the Casbin "resource:action" permission
// declared with @permission in packages/contracts.
var Permissions = map[string]string{
${body}
}
`;
  writeFileSync(join(targetDir, "permissions_gen.go"), content);
  execSync("gofmt -w permissions_gen.go", { cwd: targetDir, stdio: "inherit" });
  console.log(`  * Wrote permissions_gen.go with ${entries.length} operations`);
}
